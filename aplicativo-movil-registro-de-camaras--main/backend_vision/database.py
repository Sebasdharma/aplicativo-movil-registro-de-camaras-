def es_conexion_postgres(conn_o_cursor):
    return isinstance(conn_o_cursor, (ConexionPostgres, CursorPostgres))


def insertar_y_obtener_id(cursor, sql, parametros):
    """Ejecuta un INSERT y devuelve el id generado en SQLite o PostgreSQL."""
    if es_conexion_postgres(cursor):
        return cursor.execute(
            sql.rstrip().rstrip(";") + " RETURNING id", parametros
        ).fetchone()["id"]
    cursor.execute(sql, parametros)
    return cursor.lastrowid


def _columnas_tabla(cursor, tabla):
    if es_conexion_postgres(cursor):
        return {
            row["column_name"]
            for row in cursor.execute(
                """
                SELECT column_name FROM information_schema.columns
                WHERE table_schema = current_schema() AND table_name = ?
                """,
                (tabla,),
            ).fetchall()
        }
    return {row["name"] for row in cursor.execute(f"PRAGMA table_info({tabla})")}


def _ensure_columns(cursor, table, columns):
    existing = _columnas_tabla(cursor, table)
    for name, definition in columns.items():
        if name not in existing:
            cursor.execute(f"ALTER TABLE {table} ADD COLUMN {name} {definition}")

