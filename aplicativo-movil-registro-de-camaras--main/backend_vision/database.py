def _reemplazar_fuera_de_comillas(sql, reemplazos):
    resultado = []
    en_texto = False
    for caracter in sql:
        if caracter == "'":
            en_texto = not en_texto
            resultado.append(caracter)
        elif not en_texto and caracter in reemplazos:
            resultado.append(reemplazos[caracter])
        else:
            resultado.append(caracter)
    return "".join(resultado)


def _traducir_sql_postgres(sql, con_parametros):
    """Convierte el SQL escrito para SQLite al dialecto de PostgreSQL."""
    ignorar_conflictos = bool(_INSERT_OR_IGNORE.search(sql))
    if ignorar_conflictos:
        sql = _INSERT_OR_IGNORE.sub("INSERT INTO", sql)
    sql = sql.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ).replace("DEFAULT CURRENT_TIMESTAMP", f"DEFAULT {_FECHA_ACTUAL_POSTGRES}")
    if con_parametros:
        sql = _reemplazar_fuera_de_comillas(sql, {"%": "%%", "?": "%s"})
    if ignorar_conflictos:
        sql = sql.rstrip().rstrip(";") + "\nON CONFLICT DO NOTHING"
    return sql


class FilaPostgres:
    """Fila compatible con sqlite3.Row: fila[0], fila["columna"] y dict(fila)."""

    __slots__ = ("_nombres", "_valores", "_indices")

    def __init__(self, nombres, valores):
        self._nombres = nombres
        self._valores = tuple(valores)
        self._indices = {nombre: indice for indice, nombre in enumerate(nombres)}

    def __getitem__(self, clave):
        if isinstance(clave, (int, slice)):
            return self._valores[clave]
        return self._valores[self._indices[clave]]

    def keys(self):
        return list(self._nombres)

    def __iter__(self):
        return iter(self._valores)

    def __len__(self):
        return len(self._valores)

    def __eq__(self, otra):
        if isinstance(otra, FilaPostgres):
            return self._nombres == otra._nombres and self._valores == otra._valores
        return NotImplemented

    def __hash__(self):
        return hash(self._valores)

    def __repr__(self):
        return f"FilaPostgres({dict(zip(self._nombres, self._valores))!r})"


def _fabrica_filas(cursor):
    nombres = (
        [columna.name for columna in cursor.description]
        if cursor.description
        else []
    )

    def crear_fila(valores):
        return FilaPostgres(nombres, valores)

    return crear_fila


class CursorPostgres:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, sql, parametros=None):
        if parametros:
            self._cursor.execute(_traducir_sql_postgres(sql, True), parametros)
        else:
            self._cursor.execute(_traducir_sql_postgres(sql, False))
        return self

    def executemany(self, sql, secuencia_parametros):
        self._cursor.executemany(
            _traducir_sql_postgres(sql, True), list(secuencia_parametros)
        )
        return self

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor.fetchall())

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def description(self):
        return self._cursor.description

    @property
    def lastrowid(self):
        raise AttributeError(
            "PostgreSQL no ofrece lastrowid; usa insertar_y_obtener_id()."
        )

    def close(self):
        self._cursor.close()


class ConexionPostgres:
    """Conexión del pool con la misma interfaz que usa el código de SQLite."""

    def __init__(self, pool, conexion):
        self._pool = pool
        self._conexion = conexion

    def cursor(self):
        return CursorPostgres(self._conexion.cursor(row_factory=_fabrica_filas))

    def execute(self, sql, parametros=None):
        return self.cursor().execute(sql, parametros)

    def executemany(self, sql, secuencia_parametros):
        return self.cursor().executemany(sql, secuencia_parametros)

    def commit(self):
        self._conexion.commit()

    def rollback(self):
        self._conexion.rollback()

    def close(self):
        if self._conexion is not None:
            conexion, self._conexion = self._conexion, None
            try:
                # Igual que SQLite: lo que no se confirmó con commit() se descarta.
                conexion.rollback()
            finally:
                self._pool.putconn(conexion)

    def __enter__(self):
        return self

    def __exit__(self, tipo_error, error, traza):
        if tipo_error is None:
            self.commit()
        else:
            self.rollback()
        return False

    def __del__(self):
        try:
            self.close()
        except Exception:
            pass


def _conninfo_postgres(url):
    from psycopg.conninfo import conninfo_to_dict, make_conninfo

    parametros = conninfo_to_dict(url)
    host = str(parametros.get("host") or "")
    es_local = host in ("", "localhost", "127.0.0.1", "::1") or host.startswith("/")
    if "sslmode" not in parametros and not es_local:
        parametros["sslmode"] = "require"
    parametros.setdefault("connect_timeout", "10")
    parametros.setdefault("application_name", "asistech-backend")
    return make_conninfo(**parametros)


def _obtener_pool(url):
    with _pools_lock:
        pool = _pools.get(url)
        if pool is None:
            try:
                from psycopg_pool import ConnectionPool
            except ImportError as error:
                raise RuntimeError(
                    "Para usar PostgreSQL/Supabase instala las dependencias: "
                    "pip install -r requirements.txt"
                ) from error
            pool = ConnectionPool(
                _conninfo_postgres(url),
                min_size=1,
                max_size=int(os.environ.get("ASISTECH_DB_POOL_MAX", "5")),
                # prepare_threshold=None permite usar el pooler de Supabase.
                kwargs={"prepare_threshold": None},
                check=ConnectionPool.check_connection,
                name="asistech",
                open=True,
            )
            _pools[url] = pool
        return pool


def cerrar_pools():
    with _pools_lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


atexit.register(cerrar_pools)


